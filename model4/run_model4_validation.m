function validationResults = run_model4_validation()
scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
outputDir = fullfile(projectDir, 'results', 'model4_validation');

addpath(scriptDir);

if ~exist(outputDir, 'dir')
    mkdir(outputDir);
end

model = model4_setup(projectDir);
sweepOptions = model4_default_sin1_sweep(model, model.y0);
sweepResults = model4_run_sin1_sweep(model, model.y0, sweepOptions, struct());

diagnostics = sweepResults.biphasicDiagnostics;
summaryTable = table( ...
    {diagnostics.classification}, ...
    diagnostics.isValid, ...
    diagnostics.localPeakCount, ...
    diagnostics.peakSin1, ...
    diagnostics.peakResponse, ...
    diagnostics.lowEndpointResponse, ...
    diagnostics.highEndpointResponse, ...
    diagnostics.leftRise, ...
    diagnostics.rightDrop, ...
    diagnostics.dynamicRange, ...
    diagnostics.rightDrop / max(diagnostics.peakResponse, eps), ...
    'VariableNames', { ...
    'classification', ...
    'passes_shape_checks', ...
    'local_peak_count', ...
    'peak_sin1', ...
    'peak_pS6K1', ...
    'low_sin1_pS6K1', ...
    'high_sin1_pS6K1', ...
    'rise_from_low_sin1', ...
    'drop_to_high_sin1', ...
    'dynamic_range', ...
    'peak_to_high_suppression_fraction'});

writetable(sweepResults.sweepTable, fullfile(outputDir, 'validation_sweep_results.csv'));
writetable(summaryTable, fullfile(outputDir, 'validation_summary.csv'));
save(fullfile(outputDir, 'validation_results.mat'), ...
    'model', 'sweepOptions', 'sweepResults', 'summaryTable');

figure('Color', 'w', 'Position', [100 100 900 420]);
semilogx(sweepResults.sin1InitialValues, sweepResults.finalPs6k1, '-o', ...
    'LineWidth', 1.6, 'MarkerSize', 4, 'MarkerFaceColor', [0.1 0.4 0.8]);
hold on;
plot(diagnostics.peakSin1, diagnostics.peakResponse, 'p', ...
    'MarkerSize', 12, 'MarkerFaceColor', [0.85 0.33 0.1], 'MarkerEdgeColor', 'k');
xlabel('Initial total SIN1');
ylabel('Final pS6K1');
title('Model 4 Validation: SIN1-mTORC1 Biphasic Response');
grid on;
annotationText = sprintf(['Class: %s\\nPeak SIN1: %.4g\\nPeak pS6K1: %.4g\\n' ...
    'Low endpoint: %.4g\\nHigh endpoint: %.4g'], ...
    diagnostics.classification, ...
    diagnostics.peakSin1, ...
    diagnostics.peakResponse, ...
    diagnostics.lowEndpointResponse, ...
    diagnostics.highEndpointResponse);
text(sweepResults.sin1InitialValues(3), max(sweepResults.finalPs6k1) * 0.98, annotationText, ...
    'VerticalAlignment', 'top', 'BackgroundColor', 'w', 'Margin', 8);
saveas(gcf, fullfile(outputDir, 'validation_curve.png'));
savefig(gcf, fullfile(outputDir, 'validation_curve.fig'));
close(gcf);

fprintf('Model 4 validation complete.\n');
fprintf('Classification: %s\n', diagnostics.classification);
fprintf('Biphasic index: %.6f\n', sweepResults.biphasicIndex);
fprintf('Results written to: %s\n', outputDir);

validationResults = struct();
validationResults.model = model;
validationResults.sweepOptions = sweepOptions;
validationResults.sweepResults = sweepResults;
validationResults.summaryTable = summaryTable;
end
